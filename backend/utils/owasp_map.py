def get_owasp_category(cwe_id: Optional[str] = None, finding_type: Optional[str] = None) -> Optional[str]:
    """
    Look up the primary OWASP Top 10:2021 category for a given normalized CWE ID string.
    Special case: dependency findings (finding_type='vulnerable_dependency') map to
    A06:2021-Vulnerable and Outdated Components regardless of CWE.
    Returns string in format 'A03:2021-Injection' or None if not mapped.
    """
    if finding_type == "vulnerable_dependency":
        return "A06:2021-Vulnerable and Outdated Components"

    if not cwe_id:
        return None
    
    clean_cwe = cwe_id.strip().upper()
    if not clean_cwe.startswith("CWE-"):
        clean_cwe = f"CWE-{clean_cwe}"
        
    return CWE_TO_OWASP_2021.get(clean_cwe)
